"""Build i18n-en.js from tools/i18n-en/*.txt  (one 'ไทย ⇒ English' pair per line; {} = template slot)."""
import json, glob, os, sys
here = os.path.dirname(os.path.abspath(__file__))
d = {}
for f in sorted(glob.glob(os.path.join(here, 'i18n-en', '*.txt'))):
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('//'): continue
        k, _, v = line.partition(' ⇒ ')
        k = k.strip(); v = v.strip()
        if k in d and d[k] != v: print(f'dup {os.path.basename(f)}:{n} {k!r}: {d[k]!r} -> {v!r}', file=sys.stderr)
        d[k] = v
out = os.path.join(here, '..', 'i18n-en.js')
with open(out, 'w', encoding='utf-8') as o:
    o.write('/* Cupmori · English dictionary (generated by tools/build_i18n_en.py from tools/i18n-en/*.txt — edit those). */\n')
    o.write('window.I18N_EN = ' + json.dumps(d, ensure_ascii=False, indent=0) + ';\n')
print(len(d), 'entries')
